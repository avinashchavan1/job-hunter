// Bundles server/*.ts (+ src/shared) into supabase/functions/jh-api/index.ts.
// npm packages stay external as `npm:pkg@version` imports, which the Supabase (Deno) runtime installs.
import { build } from 'esbuild'
import { mkdirSync, readFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const version = (pkg) => JSON.parse(readFileSync(join(root, 'node_modules', pkg, 'package.json'), 'utf8')).version

const npmSpecifiers = {
  name: 'npm-specifiers',
  setup(b) {
    b.onResolve({ filter: /^[^./]/ }, (a) => {
      if (a.path.startsWith('npm:') || a.path.startsWith('node:')) return { path: a.path, external: true }
      const parts = a.path.split('/')
      const pkg = a.path.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]
      const sub = a.path.slice(pkg.length)
      return { path: `npm:${pkg}@${version(pkg)}${sub}`, external: true }
    })
  }
}

const out = join(root, 'supabase/functions/jh-api/index.ts')
mkdirSync(dirname(out), { recursive: true })
await build({
  entryPoints: [join(root, 'server/index.ts')],
  outfile: out,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  plugins: [npmSpecifiers],
  banner: { js: '// @ts-nocheck\n// GENERATED by scripts/build-functions.mjs from server/ — do not edit.' },
  logLevel: 'warning'
})
console.log('built', out)
